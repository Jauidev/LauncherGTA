"""Writes cmake/ffmpeg.cmake: libavutil and libavcodec (what Xenia's XMA decoder needs) with the
source lists of Xenia's own CMake (third_party/xenia-gpu/third_party/CMakeLists.txt), adapted to
this build: x86 files on Windows, aarch64 files plus NEON assembly on Android.
Usage: py -3 -I tools/gen-ffmpeg-cmake.py
"""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "third_party/xenia-gpu/third_party/CMakeLists.txt"), encoding="utf-8").read()
start = src.index("# --- libavutil ---")
end = src.index("# --- libavformat ---")
block = src[start:end]
block = re.sub(r"(?m)^(\s*)FFmpeg/", r"\1${XENIA_TP}/FFmpeg/", block)
block = block.replace("target_sources(libavcodec PRIVATE FFmpeg/", "target_sources(libavcodec PRIVATE ${XENIA_TP}/FFmpeg/")
block = block.replace("${CMAKE_CURRENT_SOURCE_DIR}/FFmpeg", "${XENIA_TP}/FFmpeg")
block = block.replace("XE_TARGET_X86_64", "WIN32").replace("XE_TARGET_AARCH64", "ANDROID").replace("XE_HAS_GAS_ASM", "ANDROID")
block = block.replace("xe_add_gas_sources(", "target_sources(").replace("target_sources(libavutil\n", "target_sources(libavutil PRIVATE\n").replace("target_sources(libavcodec\n", "target_sources(libavcodec PRIVATE\n")
header = '''# gta4port: generated by tools/gen-ffmpeg-cmake.py from Xenia's third_party/CMakeLists.txt.
# FFmpeg (has207 fork, commit pinned by Xenia) for the XMA decoder: libavutil and libavcodec,
# with Xenia's configuration overlay (third_party/xenia-gpu/third_party/ffmpeg-xenia).
if (ANDROID)
    enable_language(ASM)
endif()

function(ffmpeg_common target)
    target_compile_definitions(${target} PRIVATE HAVE_AV_CONFIG_H _USE_MATH_DEFINES)
    target_include_directories(${target} PRIVATE ${XENIA_TP}/ffmpeg-xenia ${XENIA_TP}/FFmpeg)
    if (WIN32)
        target_include_directories(${target} PRIVATE ${XENIA_TP}/FFmpeg/compat/atomics/win32)
        target_link_libraries(${target} PRIVATE bcrypt)
    else()
        target_include_directories(${target} PRIVATE ${XENIA_TP}/FFmpeg/compat/atomics/gcc)
        # The NEON assembly reaches FFmpeg's tables with adrp/add, which libgta4.so only allows
        # for symbols that cannot be preempted.
        target_compile_options(${target} PRIVATE -fvisibility=hidden)
    endif()
    target_compile_options(${target} PRIVATE -w)
    set_target_properties(${target} PROPERTIES LINKER_LANGUAGE C)
endfunction()

'''
open(os.path.join(root, "cmake/ffmpeg.cmake"), "w", encoding="utf-8").write(header + block)
print("written", len(block.splitlines()), "lines")
