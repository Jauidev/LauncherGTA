"""Ports LibertyRecomp's GTA IV hooks (third_party/rexglue/gta4-recomp/src) to this EFLC build.

1. tools/translate_addresses.py rewrites TU8 addresses with analysis/tu8_to_eflc_addresses.tsv.
2. Overrides are re-declared the way this runtime overrides recompiled functions: XenonRecomp emits
   `sub_X` as a weak alias with C++ linkage (PPC_WEAK_FUNC), so `extern "C" void sub_X(PPCContext&
   ctx, uint8_t* base)` becomes `PPC_FUNC(sub_X)`.
3. rexglue_glue/eflc/gta4_eflc_imports.h declares every __imp__sub_X the files call
   (PPC_FUNC_IMPL, as runtime/gpu/shadow_size.cpp does by hand).

Output: rexglue_glue/eflc/ (regenerated; edit the sources there only through patches recorded in
rexglue_glue/eflc_patches/, applied last, so a rerun keeps them).

usage: py -3 -I tools/port_native_hooks.py
"""
import glob, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "rexglue", "gta4-recomp", "src")
OUT = os.path.join(ROOT, "rexglue_glue", "eflc")
PATCHES = os.path.join(ROOT, "rexglue_glue", "eflc_patches")
TABLE = os.path.join(ROOT, "analysis", "tu8_to_eflc_addresses.tsv")

os.makedirs(OUT, exist_ok=True)
files = sorted(f for ext in ("cpp", "h", "inc", "mm")
               for f in glob.glob(os.path.join(SRC, "**", "*." + ext), recursive=True))
outputs = {f: os.path.join(OUT, os.path.relpath(f, SRC)) for f in files}
args = [sys.executable, "-I", os.path.join(ROOT, "tools", "translate_addresses.py"), TABLE]
for f in files:
    os.makedirs(os.path.dirname(outputs[f]), exist_ok=True)
    args += [f, outputs[f]]
log = subprocess.run(args, capture_output=True, text=True, check=True).stdout
with open(os.path.join(OUT, "translate.log"), "w", encoding="utf-8") as f:
    f.write(log)

# Any identifier: hook macros (#define X_HOOK(address) extern "C" void address(...)) too.
OVERRIDE = re.compile(r'extern "C" void (\w+)\(\s*PPCContext\s*&\s*(?:__restrict\s+)?ctx,\s*'
                      r'uint8_t\s*\*\s*base\s*\)')
# rex/hook.h's REX_HOOK_RAW(name) is `extern "C" REX_FUNC(name)`: same override, other spelling.
HOOK_RAW = re.compile(r"\bREX_HOOK_RAW\((sub_[0-9A-F]{8})\)")
# Every guest function named anywhere gets a __imp__ declaration: macros build __imp__##address.
IMP = re.compile(r"(?<![0-9A-Za-z])(sub_[0-9A-F]{8})\b")
# ReXGlue runtime objects the hooks reach for, replaced by rexglue_glue's (rexglue_glue.h).
REWRITES = [
    (re.compile(r"auto\* (\w+) = REX_KERNEL_STATE\(\);\s*auto\* memory = \1 \? \1->memory\(\) : nullptr;"),
     "auto* memory = ::gta4native::GuestMemory();"),
    (re.compile(r"auto\* (\w+) = rex::Runtime::instance\(\);\s*auto\* memory = \1 \? \1->memory\(\) : nullptr;"),
     "auto* memory = ::gta4native::GuestMemory();"),
    (re.compile(r"auto\* (\w+) = rex::Runtime::instance\(\);\s*auto\* window = \1 \? \1->display_window\(\) : nullptr;"),
     "auto* window = ::gta4native::DisplayWindow();"),
    (re.compile(r"auto\* (\w+) = rex::Runtime::instance\(\);\s*if \(!\1\) \{\s*return nullptr;\s*\}\s*"
                r"auto\* graphics = \1->graphics_system\(\);"),
     "auto* graphics = ::gta4native::GraphicsSystem();"),
]
# Functions this runtime hooks too (runtime/gpu/*.cpp): theirs become gta4native_sub_X, called by
# ours through GTA4_NATIVE_DISPATCH (rexglue_glue/gta4_native.h) while the native renderer runs.
SHARED = ["sub_8227A990", "sub_828DC338", "sub_82A3C858", "sub_82A3E500", "sub_82A3E998",
          "sub_82A42798", "sub_82A428A8"]
imports = set()
for f in files:
    path = outputs[f]
    text = open(path, encoding="utf-8").read()
    if path.endswith("_guest.inc"):
        # Copies of TU8 recompiled bodies with one operand changed (tools/derive_*_hooks.py in
        # LibertyRecomp): their immediates and labels are TU8's, wrong for EFLC. Dropped, so those
        # functions run unhooked; redo them from this build's bodies if the feature is wanted.
        text = ("// gta4port: emptied by tools/port_native_hooks.py (TU8 recompiled bodies, invalid "
                "for EFLC).\n")
    text = OVERRIDE.sub(r"PPC_FUNC(\1)", text)
    text = HOOK_RAW.sub(r"PPC_FUNC(\1)", text)
    for pattern, replacement in REWRITES:
        text = pattern.sub(replacement, text)
    for name in SHARED:
        text = text.replace(f"PPC_FUNC({name})", f"PPC_FUNC(gta4native_{name})")
    imports |= set(IMP.findall(text))
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write(text)

with open(os.path.join(OUT, "gta4_eflc_imports.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n\n// Generated by tools/port_native_hooks.py: the recompiled bodies the hooks call.\n")
    f.write('#include "ppc_recomp_shared.h"\n\n')
    for name in sorted(imports):
        f.write(f"PPC_FUNC_IMPL(__imp__{name});\n")

for patch in sorted(glob.glob(os.path.join(PATCHES, "*.patch"))):
    subprocess.run(["git", "apply", "--unsafe-paths", "--directory=rexglue_glue/eflc", "-p1", patch],
                   cwd=ROOT, check=True)
    print("applied", os.path.basename(patch))
print(f"{len(files)} files ported, {len(imports)} __imp__ declarations")
