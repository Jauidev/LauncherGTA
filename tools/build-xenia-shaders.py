#!/usr/bin/env python3
"""gta4port: compiles Xenia's built-in Vulkan shaders (third_party/xenia-gpu, src/xenia/gpu/shaders
and src/xenia/ui/shaders) into the SPIR-V headers its sources include (shaders/bytecode/vulkan_spirv).

Same output as Xenia's tools/build/compile_shader_spirv.py, but with the shader tools the Android
NDK ships (glslc, spirv-opt, spirv-dis) instead of the Vulkan SDK's glslangValidator.
Only shaders whose header is missing or older than any shader source are rebuilt.

Usage: py -3 tools/build-xenia-shaders.py
"""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XENIA = os.path.join(ROOT, "third_party", "xenia-gpu", "src", "xenia")
SHADER_DIRS = [os.path.join(XENIA, "gpu", "shaders"), os.path.join(XENIA, "ui", "shaders")]
NDK = os.environ.get("ANDROID_NDK", os.path.join(os.environ["LOCALAPPDATA"], "Android", "Sdk", "ndk", "27.2.12479018"))
TOOLS = os.path.join(NDK, "shader-tools", "windows-x86_64")
GLSLC = os.path.join(TOOLS, "glslc.exe")
SPIRV_OPT = os.path.join(TOOLS, "spirv-opt.exe")
SPIRV_DIS = os.path.join(TOOLS, "spirv-dis.exe")

STAGES = {"vs": "vert", "hs": "tesc", "ds": "tese", "gs": "geom", "ps": "frag", "cs": "comp"}

XESL_WRAPPER = (
    "#version 460\n"
    "#extension GL_EXT_control_flow_attributes : require\n"
    "#extension GL_EXT_samplerless_texture_functions : require\n"
    "#extension GL_GOOGLE_include_directive : require\n"
    "#include \"%s\"\n"
)


def run(args, stdin=None):
    result = subprocess.run(args, input=stdin, text=stdin is not None, capture_output=True)
    if result.returncode != 0:
        sys.stderr.write(f"FAILED: {' '.join(args)}\n")
        err = result.stderr if isinstance(result.stderr, str) else result.stderr.decode(errors="replace")
        sys.stderr.write(err)
        sys.exit(1)


def compile_shader(source, header, identifier, stage):
    base = os.path.splitext(header)[0]
    raw, opt, dis = base + ".glslc.spv", base + ".spv", base + ".txt"
    name = os.path.basename(source)
    if name.endswith(".xesl"):
        # The wrapper includes the .xesl from its own directory (read from stdin).
        run([GLSLC, f"-fshader-stage={stage}", "-DSHADING_LANGUAGE_GLSL_XE=1", f"-I{os.path.dirname(source)}",
             "--target-env=vulkan1.0", "-o", raw, "-"], stdin=XESL_WRAPPER % name)
    else:
        run([GLSLC, f"-fshader-stage={stage}", "-DSHADING_LANGUAGE_GLSL_XE=1", "--target-env=vulkan1.0",
             "-o", raw, source])
    run([SPIRV_OPT, "-O", raw, "-o", opt])
    run([SPIRV_DIS, "-o", dis, opt])

    with open(opt, "rb") as f:
        words = f.read()
    with open(dis, "r") as f:
        disassembly = f.read()
    with open(header, "w", newline="\n") as out:
        out.write("// Generated by gta4-360-port tools/build-xenia-shaders.py.\n#if 0\n")
        out.write(disassembly if disassembly.endswith("\n") else disassembly + "\n")
        out.write("#endif\n\nconst uint32_t %s[] = {" % identifier)
        for i in range(0, len(words), 4):
            if i % 24 == 0:
                out.write("\n    ")
            else:
                out.write(" ")
            out.write("0x%08X," % int.from_bytes(words[i:i + 4], "little"))
        out.write("\n};\n")
    for path in (raw, opt, dis):
        os.remove(path)


def main():
    built = 0
    for shader_dir in SHADER_DIRS:
        out_dir = os.path.join(shader_dir, "bytecode", "vulkan_spirv")
        os.makedirs(out_dir, exist_ok=True)
        sources = [n for n in os.listdir(shader_dir) if n.endswith((".xesl", ".glsl", ".xesli", ".glsli"))]
        newest = max(os.path.getmtime(os.path.join(shader_dir, n)) for n in sources)
        for name in sorted(sources):
            identifier = os.path.splitext(name)[0].replace(".", "_")
            stage = STAGES.get(identifier[-2:])
            if stage is None or name.endswith(("i")):
                continue
            header = os.path.join(out_dir, identifier + ".h")
            if os.path.exists(header) and os.path.getmtime(header) >= newest:
                continue
            compile_shader(os.path.join(shader_dir, name), header, identifier, stage)
            built += 1
    print(f"{built} shaders compiled")


if __name__ == "__main__":
    main()
