"""Generates GTA IV's copy of the port's sources: runtime/ and rexglue_glue/ with every EFLC guest
address replaced by its IV equivalent (analysis/gta4/eflc_to_iv_addresses.tsv, written by
tools/match_functions.py and tools/match_refine.py). The EFLC sources stay the only ones to edit, so
a fix is made once. CMake compiles this copy with -DGTA4_IV=ON.

Addresses without an equivalent must not stay as they are: the same number can be a different
function or global in IV. Functions become sub_EFLC_<address>, defined in the generated
rexglue_glue/iv_unmapped.cpp to log and return (a hook of one is simply never called); literals move
outside the guest image, so a comparison with them never matches.

Files whose text does not change are not rewritten, so ninja rebuilds only what changed.

usage: py -3 -I tools/gen_iv_sources.py <output dir>     (run from the project root)
"""
import os, re, sys

TABLE = "analysis/gta4/eflc_to_iv_addresses.tsv"
TREES = ("runtime", "rexglue_glue")
EXTENSIONS = (".cpp", ".h", ".inc", ".cc", ".mm", ".hpp")
# Numbers in the image's range that are not addresses of anything in it.
NOT_ADDRESSES = {0x82000000, 0x83000000, 0x82010000}

output = sys.argv[1]
table = {}
for line in open(TABLE, encoding="utf-8"):
    eflc, iv, *_ = line.rstrip("\n").split("\t")
    table[int(eflc, 16)] = None if iv == "?" else int(iv, 16)

# gta4native_sub_X: rexglue_glue/gta4_native.h renames the hooks it dispatches to that way.
SUB = re.compile(rb"\b(__imp__|gta4native_)?sub_(8[0-9A-F]{7})\b")
HEX = re.compile(rb"\b0x(8[0-9A-Fa-f]{7})(?=[uUlL]*\b)")
unmapped_functions = set()


def replace_sub(m):
    a = int(m.group(2), 16)
    prefix = m.group(1) or b""
    if a not in table:
        return m.group(0)
    if table[a] is None:
        unmapped_functions.add(a)
        return prefix + b"sub_EFLC_%08X" % a
    return prefix + b"sub_%08X" % table[a]


def replace_hex(m):
    a = int(m.group(1), 16)
    if a in NOT_ADDRESSES or a not in table:
        return m.group(0)
    if table[a] is None:
        return b"0x0F%06X" % (a & 0xFFFFFF)
    digits = m.group(1)
    return b"0x%08x" % table[a] if digits != digits.upper() else b"0x%08X" % table[a]


def write_if_changed(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    try:
        with open(path, "rb") as f:
            if f.read() == data:
                return False
    except FileNotFoundError:
        pass
    with open(path, "wb") as f:
        f.write(data)
    return True


wanted = set()
changed = total = 0
for tree in TREES:
    for root, _, names in os.walk(tree):
        for name in names:
            if not name.endswith(EXTENSIONS):
                continue
            source = os.path.join(root, name)
            with open(source, "rb") as f:
                data = HEX.sub(replace_hex, SUB.sub(replace_sub, f.read()))
            target = os.path.normpath(os.path.join(output, source))
            wanted.add(target)
            total += 1
            changed += write_if_changed(target, data)

lines = ["// Generated by tools/gen_iv_sources.py: EFLC functions with no GTA IV equivalent.",
         "#include <cstdio>", "#include <ppc_recomp_shared.h>", ""]
for a in sorted(unmapped_functions):
    lines += [f"PPC_FUNC_IMPL(__imp__sub_EFLC_{a:08X}) {{",
              f'    fprintf(stderr, "gta4-iv: EFLC function {a:08X} has no IV equivalent\\n");',
              "}",
              f"PPC_WEAK_FUNC(sub_EFLC_{a:08X}) {{ __imp__sub_EFLC_{a:08X}(ctx, base); }}", ""]
target = os.path.normpath(os.path.join(output, "rexglue_glue", "iv_unmapped.cpp"))
wanted.add(target)
changed += write_if_changed(target, "\n".join(lines).encode())

# Files removed from the sources do not stay in the copy.
for root, _, names in os.walk(output):
    for name in names:
        path = os.path.normpath(os.path.join(root, name))
        if path not in wanted:
            os.remove(path)
print(f"gen_iv_sources: {total} files, {changed} rewritten, {len(unmapped_functions)} unmapped functions")

# The renderer in third_party/ is shared, not translated: an EFLC address there silently stays wrong
# on GTA IV. They belong in guest_addresses.h, one value per game. The timecycle table holds hashes.
RENDERER = ("third_party/rexglue/src/graphics/gta4_native", "third_party/rexglue/include/rex/graphics/gta4_native")
RENDERER_EXEMPT = ("guest_addresses.h", "fusion_timecycle_data.inc")
for tree in RENDERER:
    for root, _, names in os.walk(tree):
        for name in names:
            if not name.endswith(EXTENSIONS) or name in RENDERER_EXEMPT:
                continue
            path = os.path.join(root, name)
            with open(path, "rb") as f:
                for number, line in enumerate(f, 1):
                    for m in HEX.finditer(line.split(b"//")[0]):
                        if int(m.group(1), 16) in table and int(m.group(1), 16) not in NOT_ADDRESSES:
                            print(f"gen_iv_sources: WARNING {path}:{number}: EFLC address 0x{m.group(1).decode()} in the renderer")
