"""Generates runtime/kernel/stubs_generated.cpp: a logging stub for every import the game needs
(analysis/runtime-imports.txt) that no runtime source implements yet.
Usage: gen_stubs.py   (run from the project root; rerun whenever imports get implemented)"""
import glob, re
need = [l.strip() for l in open("analysis/runtime-imports.txt") if l.strip()]
have = set()
for path in glob.glob("runtime/**/*.cpp", recursive=True):
    if path.replace("\\", "/").endswith("kernel/stubs_generated.cpp"):
        continue
    have |= set(re.findall(r"GUEST_FUNCTION_(?:HOOK|STUB)\(__imp__(\w+)", open(path, encoding="utf-8").read()))
missing = [n for n in need if n not in have]
out = ["// Generated by tools/gen_stubs.py: imports the runtime does not implement yet.",
       "// Each one logs its name the first time the game calls it and returns 0.",
       "#include <stdafx.h>", "#include <kernel/function.h>", ""]
for n in missing:
    out += [f"static uint32_t Unimplemented_{n}()", "{", '    LOG_UTILITY("not implemented");', "    return 0;", "}",
            f"GUEST_FUNCTION_HOOK(__imp__{n}, Unimplemented_{n});", ""]
# Rewritten only when it changes, so the build scripts can run this every time.
text = "\n".join(out)
path = "runtime/kernel/stubs_generated.cpp"
try:
    old = open(path).read()
except FileNotFoundError:
    old = None
if old != text:
    open(path, "w").write(text)
print(f"{len(need)} imports: {len(need) - len(missing)} implemented or stubbed in sources, {len(missing)} generated")
